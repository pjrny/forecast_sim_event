  "(function (g) {\n  var schema = " + JSON.stringify(schema) + ";\n  g.EVENT_DRAFT_SCHEMA = schema;\n  if (typeof module !== \"undefined\" && module.exports) module.exports = { schema: schema };\n})(typeof window !== \"undefined\" ? window : globalThis);\n";
fs.writeFileSync(path.join(root, "js/event_draft_schema.js"), out);
